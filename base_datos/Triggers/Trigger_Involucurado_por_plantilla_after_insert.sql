DROP TRIGGER IF EXISTS after_involucrado_por_plantilla;
DELIMITER //
CREATE TRIGGER after_involucrado_por_plantilla
AFTER INSERT ON INVOLUCRADO_POR_PLANTILLA
FOR EACH ROW
BEGIN

	-- Inserta la disponibilidad por defecto
	INSERT INTO DISPONIBILIDAD_INVOLUCRADO_POR_FECHA_TRANSPORTE (COD_INVOLUCRADO, COD_FECHA_TRANSPORTE, NECESITA_TRANSPORTE)
		SELECT NEW.COD_INVOLUCRADO, ftpp.ID, 1
			FROM FECHA_TRANSPORTE_POR_PLANTILLA ftpp
				WHERE ftpp.COD_PLANTILLA = NEW.COD_PLANTILLA;
    
END //
DELIMITER ;