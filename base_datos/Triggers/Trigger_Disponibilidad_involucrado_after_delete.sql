DROP TRIGGER IF EXISTS delete_transport_after_delete_disponibilidad;
DELIMITER //
CREATE TRIGGER delete_transport_after_delete_disponibilidad
AFTER DELETE ON DISPONIBILIDAD_INVOLUCRADO_POR_FECHA_TRANSPORTE
FOR EACH ROW
BEGIN
	
    DECLARE esInvolucradoConductor BOOLEAN;
    
    SELECT DISTINCT
		CASE WHEN 
			ipp.COD_ROL = 2 THEN TRUE
			ELSE FALSE
        END
		INTO esInvolucradoConductor
			FROM 
				INVOLUCRADO_POR_PLANTILLA ipp
					INNER JOIN FECHA_TRANSPORTE_POR_PLANTILLA ftpp
						ON ipp.COD_PLANTILLA = ftpp.COD_PLANTILLA
				WHERE 
					ipp.COD_PLANTILLA = 1
					AND ipp.COD_INVOLUCRADO = OLD.COD_INVOLUCRADO;
                
    IF esInvolucradoConductor THEN
		DELETE FROM TRANSPORTE
		WHERE 
			COD_CONDUCTOR = OLD.COD_INVOLUCRADO
            AND COD_FECHA_TRANSPORTE = OLD.COD_FECHA_TRANSPORTE;
	
    ELSE
		DELETE FROM TRANSPORTE
		WHERE 
			COD_VIAJERO = OLD.COD_INVOLUCRADO
            AND COD_FECHA_TRANSPORTE = OLD.COD_FECHA_TRANSPORTE;
        
	END IF;
	
    -- Se borran los avisos del propio involucrado
	DELETE FROM AVISO_POR_INVOLUCRADO
		WHERE 
			COD_INVOLUCRADO_AVISADO = OLD.COD_INVOLUCRADO
            AND COD_FECHA_TRANSPORTE = OLD.COD_FECHA_TRANSPORTE;
END //
DELIMITER ;